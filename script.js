      document.createElement(
        "span"
      );


    petal.className =
      "petal";


    petal.style.left =
      Math.random()
      *
      100
      +
      "%";


    petal.style.animationDuration =
      12
      +
      Math.random()
      *
      9
      +
      "s";


    petal.style.animationDelay =
      Math.random()
