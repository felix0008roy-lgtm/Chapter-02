/* =====================================================
   FM
===================================================== */

const stations = [

  88.1,
  89.4,
  90.2,
  90.8,
  91.2,
  91.5,
  91.7,
  91.8,
  91.9

];


const minFM =
  88;


const maxFM =
  108;



function wait(ms) {

  return new Promise(
    resolve => {

      setTimeout(
        resolve,
        ms
      );

    }
  );

}



function setNeedle(freq) {

  const percentage =
    (
      (freq - minFM)
      /
      (maxFM - minFM)
    )
    *
    100;


  needle.style.left =
    Math.max(
      0,
      Math.min(
        100,
        percentage
      )
    )
    +
    "%";

}



/* =====================================================
   FIND CURRENT CAPTION
===================================================== */

function getCaptionIndex(
  time
) {

  let index =
    -1;


  for (
    let i = 0;
    i < captions.length;
    i++
  ) {

    if (
      time >=
      captions[i].time
    ) {

      index =
        i;

    }

    else {

      break;

    }

  }


  return index;

}



/* =====================================================
   SHOW CAPTION
===================================================== */

function showCaption(
  index,
  animate = true
) {

  if (
    index < 0
  ) {

    captionPrev.textContent =
      "";


    captionCurrent.textContent =
      "";


    captionNext.textContent =
      captions[0]?.text
      ||
      "";


    return;

  }


  const current =
    captions[index];


  if (
    !current
  ) {

    return;

  }


  /*
    Empty caption means intentionally
    remove the lyrics during music.
  */

  if (
    current.text === ""
  ) {

    captionPrev.textContent =
      "";


    captionCurrent.textContent =
      "";


    captionNext.textContent =
      "";


    return;

  }



  /*
    UPDATE TEXT IMMEDIATELY.

    This means transition animation
    NEVER delays synchronization.
  */

  captionPrev.textContent =
    captions[
      index - 1
    ]?.text
    ||
    "";


  captionCurrent.textContent =
    current.text;


  captionNext.textContent =
    captions[
      index + 1
    ]?.text
    ||
    "";



  /*
    SMOOTH VISUAL TRANSITION ONLY
  */

  if (
    animate
    &&
    typeof captionCurrent.animate
    ===
    "function"
  ) {


    captionPrev.animate(

      [
        {
          opacity: 0,
          filter:
            "blur(2px)",
          transform:
            "translateY(5px)"
        },

        {
          opacity: 0.20,
          filter:
            "blur(1.25px)",
          transform:
            "translateY(0)"
        }
      ],

      {
        duration: 650,
        easing:
          "cubic-bezier(.22,.8,.32,1)"
      }

    );



    captionCurrent.animate(

      [
        {
          opacity: 0.15,
          filter:
            "blur(2px)",
          transform:
            "translateY(7px)"
        },

        {
          opacity: 1,
          filter:
            "blur(0px)",
          transform:
            "translateY(0)"
        }
      ],

      {
        duration: 700,
        easing:
          "cubic-bezier(.22,.8,.32,1)"
      }

    );



    captionNext.animate(

      [
        {
          opacity: 0,
          filter:
            "blur(2px)",
          transform:
            "translateY(5px)"
        },

        {
          opacity: 0.20,
          filter:
            "blur(1.25px)",
          transform:
            "translateY(0)"
        }
      ],

      {
        duration: 650,
        easing:
          "cubic-bezier(.22,.8,.32,1)"
      }

    );

  }

}



/* =====================================================
   UPDATE CAPTIONS
===================================================== */

function updateCaptions(
  force = false
) {

  const currentTime =
    radioAudio.currentTime
    ||
    0;


  const index =
    getCaptionIndex(
      currentTime
    );


  if (
    !force
    &&
    index ===
    lastCaptionIndex
  ) {

    return;

  }


  lastCaptionIndex =
    index;


  showCaption(
    index,
    !force
  );

}



/* =====================================================
   CAPTION LOOP
===================================================== */

function startCaptionLoop() {

  if (
    captionFrame
  ) {

    cancelAnimationFrame(
      captionFrame
    );

  }


  function tick() {

    updateCaptions();


    if (
      !radioAudio.paused
      &&
      !radioAudio.ended
    ) {

      captionFrame =
        requestAnimationFrame(
          tick
        );

    }

  }


  captionFrame =
    requestAnimationFrame(
      tick
    );

}



/* =====================================================
   POWER / TUNING
===================================================== */

async function bootRadio() {

  if (
    radioBooted
    ||
    radioStarting
  ) {

    return;

  }


  radioStarting =
    true;


  powerBtn.classList.add(
    "active"
  );


  signalText.textContent =
    "POWER ON";


  deckStatus.textContent =
    "SEARCHING";


  captionPrev.textContent =
    "";


  captionCurrent.textContent =
    "tuning into the broadcast...";


  captionNext.textContent =
    "";



  /*
    Start muted immediately during
    the button click.

    This satisfies browser autoplay rules.
  */

  radioAudio.pause();


  radioAudio.currentTime =
    0;


  radioAudio.volume =
    0;



  try {

    await radioAudio.play();

  }

  catch (error) {

    console.error(
      "Audio permission error:",
      error
    );


    deckStatus.textContent =
      "PRESS PLAY";


    captionCurrent.textContent =
      "press play to begin";


    radioStarting =
      false;


    return;

  }



  /* FM SCAN */

  for (
    const freq
    of stations
  ) {

    frequencyDisplay.textContent =
      freq.toFixed(1);


    setNeedle(
      freq
    );


    await wait(
      170
    );

  }



  /* LOCK STATION */

  frequencyDisplay.textContent =
    "91.9";


  setNeedle(
    91.9
  );


  signalText.textContent =
    "SIGNAL LOCKED";


  deckStatus.textContent =
    "ON AIR";


  await wait(
    250
  );



  /*
    IMPORTANT:
    RESET TO EXACTLY ZERO
    AFTER THE TUNING ANIMATION.
  */

  radioAudio.pause();


  radioAudio.currentTime =
    0;


  radioAudio.volume =
    1;



  try {

    await radioAudio.play();

  }

  catch (error) {

    console.error(
      "Broadcast play error:",
      error
    );


    deckStatus.textContent =
      "PRESS PLAY";


    radioStarting =
      false;


    return;

  }



  radioBooted =
    true;


  radioStarting =
    false;


  deckStatus.textContent =
    "PLAYING";


  document.body.classList.add(
    "is-playing"
  );



  /*
    FORCE CAPTION #1 ON SCREEN.
  */

  lastCaptionIndex =
    -999;


  showCaption(
    0,
    false
  );


  lastCaptionIndex =
    0;



  /*
    FROM THIS POINT ON,
    captions follow audio.currentTime.
  */

  startCaptionLoop();

}



/* =====================================================
   PLAY
===================================================== */

async function playBroadcast() {

  if (
    !radioBooted
  ) {

    await bootRadio();

    return;

  }


  radioAudio.volume =
    1;


  try {

    await radioAudio.play();


    deckStatus.textContent =
      "PLAYING";


    document.body.classList.add(
      "is-playing"
    );


    updateCaptions(
      true
    );


    startCaptionLoop();

  }

  catch (error) {

    console.error(
      "Play error:",
      error
    );

  }

}



